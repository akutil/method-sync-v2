"""Виклик кодуючого агента з брифом (принцип I конституції, FR-65–FR-76, NFR-3).

Java-правку пише агент, а не інструмент. Це не лінощі: принцип I прямо забороняє інструментові вводити власні шаблони
коду, власні хелпери і власний формат DTO — оформлення береться з найближчого вже реалізованого файлу бібліотеки.

Роль Python — усе детерміноване: реєстр, живий виклик, фікстура, класпас, раннер, звіряння, лог ітерацій, звіт. Роль
агента — рівно одна вузька правка складу полів і констант енамів.

Відмінності від v1: режиму реалізації з нуля немає (FR-94), тож бриф не велить виконувати скіл бібліотеки; бриф несе
розходження енамів і місце нової константи (FR-55); збій запуску, ненульовий код і таймаут агента — текст для логу, а
не виняток (FR-68).
"""
import pathlib
import subprocess

CLI = "claude"
TIMEOUT_SECONDS = 900

_BRIEF = """Ти правиш ОДИН метод у Java-бібліотеці конектора біржі.

# Що правити

- Бібліотека: {lib}
- Метод біржі: {method_path}
- Клас моделі відповіді: {model}

# Розходження, яке треба усунути

{mismatch_block}

# Вивід перевірки з попередньої ітерації

{verify_output}

# Джерело правди про склад полів і значення енамів

Жива відповідь цього прогону: {fixture_path}
Приклад із документації джерелом полів і значень БУТИ НЕ МОЖЕ — беруться лише ключі й значення з фікстури.

# Обсяг правки — вузький

Цей метод у бібліотеці ВЖЕ реалізований. Тебе покликали актуалізувати склад полів моделі і константи енамів із
розходження, і більше нічого: додай поля, яких біржа віддає більше, прибери ті, яких вона не віддає, допиши
константи енамів із розходження.

НЕ чіпай: анотації класу і полів, імпорти, порядок наявних рядків, форматування, коментарі, інші файли, крім класу
моделі й файлів енамів із розходження. Навіть якщо бачиш відхилення від стандарту бібліотеки — не виправляй його:
цей файл живе в спільному прод-коді, і такі правки ухвалює людина, а не прогін.

Нове поле оформлюй так само, як оформлені сусідні поля цього ж класу, і додавай його так, щоб ЖОДЕН наявний рядок не
зсунувся відносно інших: поле — після останнього наявного поля, гетер і сетер — після останньої наявної пари, рядок у
`toString` — перед закриваючим. Порядок полів у JSON-відповіді ролі не грає, і підганяти під нього наявний клас не
треба.
{enum_block}
Якщо помітив відхилення від стандарту — напиши про це в кінці відповіді окремим рядком, але в код не вноси.

# Еталон, який мірорити

{reference_method}

Оформлення бери звідти. Власний шаблон коду, власний хелпер і власний формат DTO вводити заборонено, навіть якщо
вийшло б коротше.

# Перевірка після правки

Тобі дозволена рівно одна команда, дослівно: `{verify_cmd}`. Запусти її після правки і повертайся лише з зеленим
виводом — червоний правиш далі. Звіряння складу полів і значень енамів із фікстурою зробить інструмент після тебе;
його не імітуй.

# Межі

- Пиши лише всередині {lib}. Жодного файлу за її межами.
- Нічого не додавай в індекс і не чіпай історію репозиторію — це робота людини.
- Тестів бібліотеки не запускай і не редагуй.
- Файли з обліковими даними не відкривай.

Зроби правку і зупинись. Крім рядків про відхилення, нічого не пояснюй."""

# FR-55, FR-53: кожне речення про запасник — одним рядком, щоб «запасник» і місце константи не розійшлися.
_ENUM_BLOCK = """
# Константи енамів — лише дописати

Кожне значення енама з розходження допиши константою — і тільки допиши.
Оформлюй нову константу так само, як сусідні, і став її після останньої наявної константи, а якщо в енамі є запасник `@JsonEnumDefaultValue` — перед запасником.
Якщо запасника немає, а остання наявна константа закінчується `;`, нова константа стає після неї, а цей `;` стає `,` — це єдина дозволена зміна наявного рядка енама.
Наявні константи не видаляй, не перейменовуй і не переставляй — зокрема ті, яких не було в живій відповіді: вибірка не є покриттям.
Запасник `@JsonEnumDefaultValue` не чіпай.
"""

_STAGE_ADVICE = {
    "compile": "Бібліотека не проходить команди перевірки. Спершу полагодь це — склад полів звіряти нема на чому.",
    "javac": "Перевірочний раннер не зібрався проти класів бібліотеки.",
    "timeout": "Перевірочний раннер не завершився вчасно. Вердикту про склад полів цього разу немає.",
}


def _mismatch_block(mismatch):
    """Розходження словами: які поля прибрати, які додати, які значення енамів дописати (FR-71).

    Коли звіряння не відбулося, множин полів у вердикті немає взагалі. Перший живий прогін v1 показав, у що це
    виливається: бриф друкував порожнє тире, і агент лишався без жодної підказки, що не так. Тож тут — стадія і
    причина, і жодного переліку полів.
    """
    stage = mismatch.get("stage")
    if stage:
        text = f"Звіряння не відбулося — стадія `{stage}`: {mismatch.get('reason') or '—'}"
        advice = _STAGE_ADVICE.get(stage)
        return f"{text}\n{advice}" if advice else text
    lines = [
        f"- Зайві в моделі (біржа їх не віддає — прибрати): {', '.join(mismatch.get('extra') or []) or '—'}",
        f"- Бракує в моделі (біржа їх віддає — додати): {', '.join(mismatch.get('missing') or []) or '—'}",
    ]
    for entry in _enum_mismatches(mismatch):
        lines.append(f"- Енам поля `{entry['field']}` — клас `{entry['enum']}`: значення, яких він не оголошує "
                     f"(дописати константами): {', '.join(entry['missing'])}")
    if mismatch.get("client_error"):
        lines.append(f"- Клієнт бібліотеки кинув виняток: {mismatch['client_error']}")
    return "\n".join(lines)


def _enum_mismatches(mismatch):
    return [entry for entry in mismatch.get("enums") or [] if entry.get("missing")]


def build_brief(*, lib, method_path, model, reference_method, fixture_path, mismatch, verify_output, verify_cmd):
    """Зібрати бриф: усе, на що агент має спиратися, і нічого зайвого (FR-71–FR-76, FR-55).

    Обсяг правки — лише склад полів і константи енамів із розходження, і це рішення власника коду від 2026-09-23:
    перший живий прогін v1 показав, що агент, якому дали стандарт стилю, заодно дописав у клас анотацію, якої там
    ніколи не було. Формально правильно, але інструмент покликали повернути поле, а не переписувати чужий файл.
    Невидимих констант енама бриф не називає: прибрати їх він не просить (FR-53).
    """
    return _BRIEF.format(
        lib=lib,
        method_path=method_path,
        model=model,
        mismatch_block=_mismatch_block(mismatch),
        verify_output=verify_output or "(вивід перевірки порожній)",
        fixture_path=fixture_path,
        enum_block=_ENUM_BLOCK if _enum_mismatches(mismatch) else "",
        reference_method=reference_method,
        verify_cmd=verify_cmd,
    )


def command(brief, add_dirs=(), allowed_commands=(), lib=None):
    """Рядок запуску агента в headless-режимі (FR-65–FR-67).

    `add_dirs` потрібен не для краси: агент працює з кореня бібліотеки, а фікстура лежить у каталозі інструмента.
    Перший живий прогін v1 це й показав — агент написав «фікстуру не прочитав, вона поза дозволеним каталогом».

    Режим — `dontAsk`: усе, чого немає в `--allowedTools`, відхиляється без запиту. `acceptEdits` для цього не
    годиться — проба R-017 показала, що в ньому агент виконав `touch` і `rm` та дописав у фікстуру в `runs/`. Тож
    перелік явний: `Read`, `Edit` і `Write` лише під `lib` і рівно команда перевірки з реєстру — без неї агент
    повертав правку зі словами «mvn потребує дозволу». Шлях у `Edit(…)`/`Write(…)` — абсолютний `lib` із префіксом
    `/` (тобто `//…`): однослешний Claude Code читає відносно файлу налаштувань, і такий дозвіл не дає правити нічого
    (R-017). Без `lib` файлових дозволів немає зовсім.
    """
    argv = [CLI, "-p", brief, "--permission-mode", "dontAsk"]
    for directory in add_dirs:
        argv += ["--add-dir", str(directory)]
    tools = []
    if lib is not None:
        tools += ["Read", f"Edit(/{lib}/**)", f"Write(/{lib}/**)"]
    tools += [f"Bash({shell_line})" for shell_line in allowed_commands]
    if tools:
        argv += ["--allowedTools", *tools]
    return argv


def _seconds(limit):
    return f"{limit:g}" if isinstance(limit, float) else str(limit)


def _decoded(data):
    if isinstance(data, bytes):
        return data.decode("utf-8", "replace")
    return data or ""


def invoke(brief, cwd, add_dirs=(), allowed_commands=(), timeout=TIMEOUT_SECONDS):
    """Покликати агента і віддати текст для логу ітерації. Не кидає: падіння агента — не падіння прогону (FR-68).

    stdin — порожній навмисно: інакше агент успадковує stdin прогону, чекає на дані з труби і дописує в лог
    попередження «no stdin data received». Бриф іде аргументом, без шелу.

    Дозволи на правку — рівно під `cwd`, абсолютним і з розв'язаними посиланнями: це той самий каталог, який агент
    бачить робочим, і той самий `lib`, який CLI кладе в бриф.
    """
    try:
        lib = pathlib.Path(cwd).resolve()
        result = subprocess.run(
            command(brief, add_dirs, allowed_commands, lib=lib), cwd=str(cwd), capture_output=True, text=True,
            encoding="utf-8", errors="replace", timeout=timeout, stdin=subprocess.DEVNULL)
    except subprocess.TimeoutExpired as expired:
        partial = _decoded(expired.stdout) + _decoded(expired.stderr)
        text = f"агент не вклався в {_seconds(timeout)} с і зупинений"
        return f"{text}\n--- що агент устиг надрукувати ---\n{partial}" if partial else text
    except (OSError, ValueError, RuntimeError) as error:
        return f"агента не вдалося запустити: {error}"
    output = (result.stdout or "") + (result.stderr or "")
    if result.returncode != 0:
        return f"виклик агента не вдався: код {result.returncode}\n{output}"
    return output
